"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const formulaSource = fs.readFileSync("formula-library.js", "utf8");
const start = formulaSource.indexOf("  const formulas = [");
const end = formulaSource.indexOf("  window.MathFormulaLibraryData", start);
assert.ok(start >= 0 && end > start, "formula library should expose its source data");
const context = vm.createContext({ window: {} });
vm.runInContext(formulaSource.slice(start, end).replace("  const formulas =", "  globalThis.formulas ="), context);
const formulas = context.formulas;
assert.equal(formulas.length, 33, "all 33 formula references should become study cards");
assert.equal(new Set(formulas.map(item => item.id)).size, formulas.length, "every formula should have a stable unique ID");
assert.ok(formulas.every(item => item.title && item.category && item.tex && item.note), "each card should contain a prompt, category, expression, and explanation");
assert.deepEqual([...new Set(formulas.map(item => item.category))], ["الجبر","التحليل","المثلثات","الهندسة","المتجهات","الاحتمالات"], "all six curriculum categories should be represented");
assert.equal(formulas.filter(item => item.category === "التحليل").length, 8, "analysis deck should contain eight cards");
const source = fs.readFileSync("flashcards.js", "utf8");
for (const token of ["mathBacSyriaFlashcardsV1","MathFormulaLibraryData","flashcard-known","flashcard-review","flashcard-shuffle","flashcard-reset","typesetPromise"]) assert.ok(source.includes(token), "flashcard module should support " + token);
assert.ok(!/eval\s*\(|new Function/.test(source), "flashcard module must not execute dynamic code");
console.log("PASS: 33 formula flashcards, six subject decks, unique IDs, ratings, persistence, and safe rendering");

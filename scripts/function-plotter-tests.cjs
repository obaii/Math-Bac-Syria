#!/usr/bin/env node
"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const source = fs.readFileSync(require("node:path").join(__dirname, "..", "function-plotter.js"), "utf8");
const context = { window: {}, Number, Math, Object, Set };
vm.runInNewContext(source, context, { timeout: 5000 });
const plot = context.window.FunctionPlotter;
assert.ok(plot && typeof plot.evaluate === "function", "the plotter should expose its safe evaluator");
const close = (actual, expected, message) => assert.ok(Math.abs(actual - expected) < 1e-10, message + ": " + actual);
close(plot.evaluate("x^2", 3), 9, "square function");
close(plot.evaluate("x^2+2*x+1", 2), 9, "operator precedence");
close(plot.evaluate("-(x+2)^2", 1), -9, "unary and parentheses");
close(plot.evaluate("2^3^2", 2), 512, "right-associative exponent");
close(plot.evaluate("sin(pi/2)", 0), 1, "sine in radians");
close(plot.evaluate("sin(30)", 0, "deg"), 0.5, "sine in degrees");
close(plot.evaluate("cos(0)+sqrt(16)", 0), 5, "cosine and square root");
close(plot.evaluate("ln(e)", 0), 1, "natural logarithm");
close(plot.evaluate("log(100)+abs(-2)", 0), 4, "common logarithm and absolute value");
close(plot.evaluate("exp(0)", 0), 1, "exponential");
assert.throws(() => plot.evaluate("1/0", 0), /قسمة/);
assert.throws(() => plot.evaluate("sqrt(-1)", 0), /غير معرّفة|غير سالبة/);
assert.throws(() => plot.evaluate("ln(0)", 0), /موجبة/);
assert.throws(() => plot.evaluate("tan(pi/2)", 0), /غير معرّف/);
assert.throws(() => plot.evaluate("x+unknown", 1), /غير مدعوم/);
assert.throws(() => plot.evaluate("x;alert(1)", 1), /غير مسموح/);
assert.throws(() => plot.evaluate("x+(", 1), /الأقواس|غير مكتمل/);
assert.throws(() => plot.evaluate("x**2", 1), /الأقواس|غير مكتمل|صياغة/);
assert.throws(() => plot.evaluate("", 1), /أدخل/);
assert.throws(() => plot.evaluate("x", Infinity), /غير صالحة/);
const css = fs.readFileSync(require("node:path").join(__dirname, "..", "style-overrides.css"), "utf8");
assert.match(css, /\.plotter-controls input,\.plotter-controls select\s*\{[^}]*min-height:44px/,
  "plotter input and selector controls should provide 44px touch targets");
assert.match(css, /\.plotter-controls button\s*\{[^}]*min-height:44px/,
  "plotter action buttons should provide 44px touch targets");
const app = fs.readFileSync(require("node:path").join(__dirname, "..", "index.html"), "utf8");
assert.ok(app.includes('id="function-plotter"'), "the graph panel should be present");
assert.ok(app.includes('src="function-plotter.js?v=20261102-1"'), "the graph script should be loaded");
assert.ok(!/\beval\s*\(|\bnew\s+Function\s*\(/.test(source), "the plotter must not use dynamic code execution");
console.log("PASS: function plotter parser, mathematical functions, angle modes, invalid domains, and safe-expression checks");
"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const source = fs.readFileSync(require("node:path").join(__dirname, "..", "scientific-calculator.js"), "utf8");
const window = {};
vm.runInNewContext(source, { window, document: undefined, console, Math, Number, Object, Set, Error });
const calc = window.ScientificCalculator;
assert.ok(calc, "calculator API is exposed for isolated tests");
const close = (actual, expected, message) => assert.ok(Math.abs(actual - expected) < 1e-10, message || (String(actual) + " != " + String(expected)));
close(calc.evaluate("2+3*4"), 14, "operator precedence");
close(calc.evaluate("(2+3)*4"), 20, "parentheses");
close(calc.evaluate("2^3^2"), 512, "right-associative powers");
close(calc.evaluate("-2^2"), -4, "unary minus precedence");
close(calc.evaluate("sqrt(81)+abs(-2)"), 11, "square root and absolute value");
close(calc.evaluate("ln(e)"), 1, "natural logarithm");
close(calc.evaluate("log(1000)"), 3, "base-ten logarithm");
close(calc.evaluate("exp(0)"), 1, "exponential function");
close(calc.evaluate("sin(30)+cos(60)"), 1, "degree mode");
close(calc.evaluate("sin(pi/2)", "rad"), 1, "radian mode");
close(calc.evaluate("tan(0)"), 0, "tangent");
close(calc.evaluate("pi+e"), Math.PI + Math.E, "constants");
assert.throws(() => calc.evaluate("1/0"), /القسمة على صفر/);
assert.throws(() => calc.evaluate("sqrt(-1)"), /غير سالب/);
assert.throws(() => calc.evaluate("ln(0)"), /موجب/);
assert.throws(() => calc.evaluate("tan(90)"), /غير معرّف/);
assert.throws(() => calc.evaluate("(2+3"), /ترتيب/);
assert.throws(() => calc.evaluate("2+"), /تعبير غير مكتمل|ترتيب/);
assert.throws(() => calc.evaluate("2;alert(1)"), /رمز غير مسموح/);
assert.throws(() => calc.evaluate("window"), /غير مدعوم/);
assert.throws(() => calc.evaluate("2**3"), /ترتيب/);
assert.throws(() => calc.evaluate(""), /أدخل تعبيراً/);
console.log("Scientific calculator tests: all checks passed.");
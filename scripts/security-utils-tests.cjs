"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const source = fs.readFileSync(path.join(__dirname, "..", "security-utils.js"), "utf8");
const context = { window: {}, URL };
vm.runInNewContext(source, context);
const security = context.window.MathBacSecurity;
assert.equal(security.safeAssistantApiBase("https://assistant.example.workers.dev/"), "https://assistant.example.workers.dev");
assert.equal(security.safeAssistantApiBase("http://localhost:8787"), "http://localhost:8787");
assert.equal(security.safeAssistantApiBase("http://127.0.0.1:8787"), "http://127.0.0.1:8787");
assert.equal(security.safeAssistantApiBase("http://localhost.attacker.invalid"), "");
assert.equal(security.safeAssistantApiBase("http://127.0.0.1.attacker.invalid"), "");
assert.equal(security.safeAssistantApiBase("http://localhost.evil:8080"), "");
assert.equal(security.safeAssistantApiBase("javascript:alert(1)"), "");
assert.equal(security.safeAssistantApiBase("ftp://assistant.example"), "");
assert.equal(security.safeAssistantApiBase("https://user:pass@assistant.example"), "");
assert.equal(security.safeAssistantApiBase("https://assistant.example/?token=secret"), "");
assert.equal(security.safeHttpsUrl("https://source.example/path"), "https://source.example/path");
assert.equal(security.safeHttpsUrl("javascript:alert(1)"), "");
assert.equal(security.safeHttpsUrl("data:text/html,hello"), "");
assert.equal(security.safeHttpsUrl("http://source.example/path"), "");
assert.equal(security.safeHttpsUrl("https://user:pass@source.example/path"), "");
console.log("PASS: AI endpoints require HTTPS or exact localhost hosts; source links require credential-free HTTPS URLs.");

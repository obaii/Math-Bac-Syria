"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const source = fs.readFileSync(path.join(__dirname, "..", "search-utils.js"), "utf8");
const context = { window: {} };
vm.runInNewContext(source, context);
const search = context.window.MathSearchUtils;
assert.equal(search.normalize("أَشِعَّةُ في الْفَراغ"), "اشعة في الفراغ");
assert.equal(search.normalize("مُشْتَقَّة"), "مشتقة");
assert.equal(search.normalize("إِنَّ ٢٠٢٥"), "ان 2025");
assert.equal(search.normalize("ﻻ"), "لا");
assert.equal(search.matches("الأشعة في الفراغ", "الاشعة الفراغ"), true, "alif variants and reordered multiword terms should match");
assert.equal(search.matches("مبرهنة دي موافر", "مُبرهنة موافر دي"), true, "diacritics and term order should not block a match");
assert.equal(search.matches("استقلال حادثتين", "استقلالُ حادثتين"), true, "Arabic diacritics should be ignored");
assert.equal(search.matches("الدورة الأولى لعام ٢٠١٧", "2017"), true, "Arabic-Indic digits should match western digits");
assert.equal(search.matches("مشتقة تابع", "مشتقة تكامل"), false, "all meaningful query terms must match");
assert.deepEqual(Array.from(search.tokenize("في المشتقة ٢٠٢٥")), ["المشتقة", "2025"], "common short prepositions should not create noisy matches");
console.log("PASS: Arabic search normalization handles diacritics, alef/yaa variants, Arabic digits, punctuation, and AND matching.");
